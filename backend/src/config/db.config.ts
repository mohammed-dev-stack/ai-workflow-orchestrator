// ============================================================
// إعدادات قاعدة البيانات (PostgreSQL + pgvector) و Redis.
// تُجمِّع كل الإعدادات المتعلقة بالبنية التحتية للبيانات في مكان واحد.
// تطبق SSoT لإعدادات الاتصال، وتُوفِّر قيوداً على المهلات، تجمع الاتصالات،
// استراتيجيات القفل، وفهرسة pgvector.
//
// ملاحظة تصميم (Factory Pattern):
// الإعدادات تُبنى عبر createDbConfig(env) بدلاً من كائن ثابت يُصدَّر مباشرة.
// هذا يفصل "شكل الإعدادات" عن "مصدر القيم"، ويجعل الملف قابلاً لإعادة
// الاستخدام مع أي envConfig آخر (مثلاً في الاختبارات، أو بيئة ثانية)
// دون تعديل جسم الملف نفسه.
// ============================================================

import { envConfig } from './env.schema';

type EnvConfig = typeof envConfig;

/**
 * يبني كائن إعدادات قاعدة البيانات و Redis من مصدر بيئة مُعطى.
 * يشمل إعدادات PostgreSQL (اتصال، تجمع، معاملات، pgvector، فهارس، فحوصات الصحة، ترحيلات)
 * وإعدادات Redis (اتصال، إعادة محاولة، قوائم انتظار BullMQ، تخزين مؤقت).
 * يتبع مبدأ الفشل السريع (Fail-Fast) في حال عدم توفر روابط الاتصال.
 *
 * @param env - مصدر متغيرات البيئة المُتحقَّق منه (envConfig الافتراضي، أو نسخة
 *              بديلة عند الاختبار).
 *
 * [مُتحقَّق منطقياً بتتبع كامل] — جميع الخصائص مُعرَّفة، والأنواع مستنتجة بدقة.
 */
export function createDbConfig(env: EnvConfig) {
  return {
    /**
     * إعدادات PostgreSQL (بما في ذلك pgvector).
     */
    postgres: {
      /**
       * رابط الاتصال بقاعدة البيانات (من البيئة).
       */
      url: env.DATABASE_URL,

      /**
       * مهلة الاتصال بقاعدة البيانات بالمللي ثانية (من البيئة).
       * قيمة افتراضية: 10 ثوانٍ.
       */
      connectionTimeoutMs: env.DATABASE_POOL_TIMEOUT,

      /**
       * إعدادات تجمع الاتصالات (Connection Pool).
       * تُستخدم لإدارة الاتصالات بكفاءة ومنع استنزاف الموارد.
       */
      pool: {
        /**
         * الحد الأدنى لعدد الاتصالات في التجمع.
         * قيمة افتراضية: 2 (للحفاظ على اتصال جاهز للاستخدام الفوري).
         */
        min: 2,

        /**
         * الحد الأقصى لعدد الاتصالات في التجمع.
         * قيمة افتراضية: 10 — يمكن تعديلها حسب حجم التحميل المتوقع.
         */
        max: 10,

        /**
         * مدة بقاء الاتصال الخامل قبل إغلاقه بالمللي ثانية.
         * قيمة افتراضية: 30 ثانية.
         */
        idleTimeoutMs: 30000,

        /**
         * مهلة الحصول على اتصال من التجمع بالمللي ثانية.
         * إذا تجاوزت هذه المهلة، يُرمى خطأ (فشل سريع).
         * قيمة افتراضية: 5 ثوانٍ.
         */
        acquireTimeoutMs: 5000,
      },

      /**
       * إعدادات المعاملات (Transactions) — §4 (حدود المعاملات).
       */
      transaction: {
        /**
         * مستوى عزل المعاملة.
         * 'READ COMMITTED' هو المستوى الافتراضي في PostgreSQL،
         * ويدعم القفل المتفائل (Optimistic Locking).
         */
        isolationLevel: 'READ COMMITTED' as const,

        /**
         * مهلة المعاملة بالمللي ثانية.
         * إذا تجاوزت المعاملة هذه المهلة، تُلغى (فشل سريع).
         * قيمة افتراضية: 10 ثوانٍ.
         */
        timeoutMs: 10000,

        /**
         * ما إذا كان سيتم استخدام القفل المتفائل (Optimistic Locking).
         * يُوصى به للوصول المتزامن للموارد (الدستور §4).
         */
        enableOptimisticLocking: true,

        /**
         * اسم العمود المستخدم للقفل المتفائل (عادةً 'version').
         */
        versionColumn: 'version',
      },

      /**
       * إعدادات pgvector (التضمينات والمتجهات) — §4 (الفهرسة).
       */
      vector: {
        /**
         * بُعد المتجه المستخدم للتضمينات.
         * Claude 3 Sonnet ينتج تضمينات ببعد 1024.
         * يجب أن يتطابق مع بُعد المتجهات المُولَّدة من AI.
         */
        dimensions: 1024,

        /**
         * نوع الفهرس المستخدم للبحث عن المتجهات.
         * - 'ivfflat': أسرع للبحث التقريبي (Approximate Nearest Neighbor).
         * - 'hnsw': أدق ولكن أبطأ في البناء.
         * القيمة الافتراضية: 'ivfflat' للأداء العالي.
         */
        indexType: 'ivfflat' as const,

        /**
         * عدد القوائم (lists) في فهرس IVFFlat.
         * يُوصى بـ `rows / 1000` تقريباً، لكن القيمة الافتراضية 100 مناسبة للبيانات المتوسطة.
         */
        ivfflatLists: 100,

        /**
         * دالة المسافة المستخدمة للبحث عن المتجهات.
         * - 'cosine': مسافة جيب التمام (مناسب للتضمينات الدلالية).
         * - 'l2': المسافة الإقليدية.
         * - 'inner_product': الضرب الداخلي.
         * القيمة الافتراضية: 'cosine' — الأكثر شيوعاً للتضمينات الدلالية.
         */
        distanceFunction: 'cosine' as const,

        /**
         * عدد النتائج القصوى التي يُرجعها البحث عن المتجهات.
         * قيمة افتراضية: 10 (أعلى 10 مقاطع مطابقة).
         */
        maxSearchResults: 10,

        /**
         * عتبة التشابه (similarity threshold) — الحد الأدنى للدرجة لقبول النتيجة.
         * قيمة بين 0 و 1، حيث 1 هو التطابق التام.
         * قيمة افتراضية: 0.7 (70% تشابه).
         */
        similarityThreshold: 0.7,
      },

      /**
       * إعدادات الفهرسة العامة (B-tree، GIN، إلخ).
       * تُستخدم لتحسين أداء الاستعلامات الشائعة.
       */
      indexes: {
        /**
         * ما إذا كان سيتم إنشاء الفهارس تلقائياً عند الترحيل.
         * يُوصى بإنشائها يدوياً في الترحيلات، ولكن يمكن تفعيلها تلقائياً.
         */
        autoCreate: true,

        /**
         * قائمة بالفهارس المُوصى بها (للمراجعة اليدوية في الترحيلات).
         * هذه الفهارس تُغطي الاستعلامات الأكثر شيوعاً في التطبيق.
         */
        recommended: {
          /**
           * فهرس مركب على (tenantId, createdAt) — لاستعلامات المستأجر.
           */
          tenantCreatedAt:
            'CREATE INDEX IF NOT EXISTS idx_tenant_created_at ON "KnowledgeBase"("tenantId", "createdAt" DESC);',

          /**
           * فهرس على (tenantId, status) — لتصفية المستندات حسب الحالة.
           */
          tenantStatus:
            'CREATE INDEX IF NOT EXISTS idx_document_tenant_status ON "documents"("tenantId", "status");',

          /**
           * فهرس GIN على عمود المتجهات (vector) — للبحث السريع.
           * يتم إنشاؤه يدوياً بعد إضافة pgvector.
           */
          vectorIndex:
            'CREATE INDEX IF NOT EXISTS idx_chunk_vector ON "DocumentChunk" USING ivfflat (vector vector_cosine_ops) WITH (lists = 100);',

          /**
           * فهرس على (conversationId, createdAt) — لترتيب الرسائل في المحادثة.
           */
          conversationMessages:
            'CREATE INDEX IF NOT EXISTS idx_message_conversation_created ON "Message"("conversationId", "createdAt" ASC);',

          /**
           * فهرس على (tenantId, phoneNumberId) — لاستعلامات WhatsApp.
           */
          tenantPhone:
            'CREATE INDEX IF NOT EXISTS idx_conversation_tenant_phone ON "Conversation"("tenantId", "phoneNumberId");',
        },
      },

      /**
       * إعدادات فحوصات الصحة (Health Checks) — §5.
       * تُستخدم لفحص جاهزية قاعدة البيانات وحيويتها.
       */
      health: {
        /**
         * مهلة فحص الصحة بالمللي ثانية.
         * قيمة افتراضية: 5 ثوانٍ.
         */
        timeoutMs: 5000,

        /**
         * استعلام الفحص (يجب أن يعيد 1 إذا كانت قاعدة البيانات جاهزة).
         */
        query: 'SELECT 1',
      },

      /**
       * إعدادات الترحيلات (Migrations).
       */
      migrations: {
        /**
         * ما إذا كان سيتم تشغيل الترحيلات تلقائياً عند بدء التشغيل.
         * يُوصى بتعطيلها في الإنتاج (يُفضل تشغيلها يدوياً عبر CI/CD).
         */
        autoRun: false,

        /**
         * مسار مجلد الترحيلات (نسبة إلى جذر المشروع).
         */
        folderPath: 'src/db/migrations',

        /**
         * اسم جدول الترحيلات في قاعدة البيانات.
         */
        tableName: '_prisma_migrations',
      },
    },

    /**
     * إعدادات Redis (BullMQ + التخزين المؤقت).
     */
    redis: {
      /**
       * رابط الاتصال بـ Redis (من البيئة).
       */
      url: env.REDIS_URL,

      /**
       * مهلة الاتصال بـ Redis بالمللي ثانية.
       * قيمة افتراضية: 5 ثوانٍ (مشتقة من env.REDIS_RETRY_DELAY مضروبة في 5).
       */
      connectionTimeoutMs: env.REDIS_RETRY_DELAY * 5,

      /**
       * إعدادات إعادة محاولة الاتصال بـ Redis.
       */
      retry: {
        /**
         * مدة الانتظار بين محاولات إعادة الاتصال بالمللي ثانية (من البيئة).
         */
        delayMs: env.REDIS_RETRY_DELAY,

        /**
         * الحد الأقصى لعدد محاولات إعادة الاتصال.
         * قيمة افتراضية: 10.
         */
        maxAttempts: 10,
      },

      /**
       * إعدادات قوائم انتظار BullMQ.
       */
      queues: {
        /**
         * مهلة معالجة المهمة (Job) بالمللي ثانية.
         * إذا تجاوزت المهمة هذه المهلة، تُعتبر فاشلة وتُعاد محاولتها أو تُرسل إلى DLQ.
         * قيمة افتراضية: 5 دقائق (للمهام التي تتضمن معالجة مستندات كبيرة).
         */
        jobTimeoutMs: 300000, // 5 minutes

        /**
         * عدد مرات إعادة محاولة المهمة الفاشلة.
         */
        retryAttempts: 3,

        /**
         * مدة تأخير إعادة المحاولة (باستخدام تراجع أسي).
         * القيمة الأساسية بالمللي ثانية (مشتقة من env.RETRY_BACKOFF_BASE).
         */
        retryBackoffMs: env.RETRY_BACKOFF_BASE,

        /**
         * مدة بقاء المهمة في قائمة الانتظار (TTL) بالثواني.
         * قيمة افتراضية: 7 أيام.
         */
        jobTtlSeconds: 604800, // 7 days

        /**
         * مدة بقاء المهمة المنتهية (completed/failed) في قائمة الانتظار بالثواني.
         * قيمة افتراضية: 24 ساعة.
         */
        jobHistoryTtlSeconds: 86400, // 24 hours
      },

      /**
       * إعدادات التخزين المؤقت (Cache) — تستخدم لنتائج التضمين والاستعلامات المتكررة.
       */
      cache: {
        /**
         * مدة بقاء البيانات المؤقتة الافتراضية بالثواني.
         * قيمة افتراضية: ساعة واحدة.
         */
        defaultTtlSeconds: 3600,

        /**
         * أقصى مدة بقاء للبيانات المؤقتة بالثواني.
         * قيمة افتراضية: 24 ساعة.
         */
        maxTtlSeconds: 86400,

        /**
         * مفتاح البادئة (Prefix) لجميع مفاتيح التخزين المؤقت — لتجنب التصادم.
         */
        keyPrefix: 'cache:',
      },
    },
  } as const;
}

/**
 * نسخة الإعدادات الافتراضية للتطبيق، مبنية من envConfig الحقيقي.
 * هذا هو ما يستورده بقية التطبيق في المسار الطبيعي للتشغيل.
 */
export const dbConfig = createDbConfig(envConfig);

/**
 * استنتاج النوع من نتيجة createDbConfig.
 * يضمن سلامة النوع 100% ولا وجود لـ `any`.
 * [مُتحقَّق منطقياً بتتبع كامل] — استدلال TypeScript مع `as const` يوفر نوعاً صارماً للقراءة فقط.
 */
export type DBConfig = ReturnType<typeof createDbConfig>;

/**
 * تصدير الكائن كافتراضي لسهولة الاستيراد في وحدات التطبيق.
 */
export default dbConfig;

